#!/usr/bin/env python3
"""
Bundle the sprite strips as data URLs for playing straight from file://.

A browser treats an image read from disk as cross-origin, so drawing it taints
the canvas and the game could not export icons from it. The data URLs in
``assets/sprites.inline.js`` do not have that problem, and only file:// play
loads that file. It is rebuilt by tools/build_sprites.py, or directly with:

    python3 tools/build_inline_sprites.py
"""

from __future__ import annotations

import base64
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ASSETS = os.path.join(os.path.dirname(HERE), "assets")
OUTPUT = os.path.join(ASSETS, "sprites.inline.js")


def sprite_paths() -> list[str]:
    with open(os.path.join(ASSETS, "manifest.js"), encoding="utf-8") as f:
        text = f.read()
    manifest = json.loads(text[text.index("{"): text.rindex("}") + 1])
    paths = {entry["src"] for group in manifest.values() if isinstance(group, dict)
             for entry in group.values() if isinstance(entry, dict) and "src" in entry}
    return sorted(paths)


def build() -> int:
    sprites = {}
    for src in sprite_paths():
        with open(os.path.join(ASSETS, src), "rb") as f:
            sprites[src] = "data:image/png;base64," + base64.b64encode(f.read()).decode("ascii")
    with open(OUTPUT, "w", encoding="utf-8") as f:
        f.write("// Generated by tools/build_inline_sprites.py — do not edit.\n")
        f.write("// Sprite strips as data URLs, loaded only when the game runs from file://.\n")
        f.write("window.BC_INLINE_SPRITES = " + json.dumps(sprites, indent=0) + ";\n")
    return len(sprites)


if __name__ == "__main__":
    print(f"bundled {build()} sprites into {os.path.relpath(OUTPUT)}")
